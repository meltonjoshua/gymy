import { Workout } from '@/types/workout';
import { exercises } from './exercises';

function se(exerciseId: string, order: number, sets: number, reps: number, rest: number) {
  const ex = exercises.find((e) => e.id === exerciseId);
  if (!ex) throw new Error(`Exercise not found: ${exerciseId}`);
  return {
    id: `tpl-${exerciseId}-${order}`,
    exerciseId,
    order,
    sets: Array.from({ length: sets }, (_, i) => ({
      id: `tpl-s-${exerciseId}-${order}-${i + 1}`,
      exerciseId,
      setNumber: i + 1,
      reps,
      weight: 0,
      completed: false,
    })),
    restSeconds: rest,
    notes: '',
  };
}

